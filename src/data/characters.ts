export interface Look {
  skin: string
  hair: string
  hairStyle: 'short' | 'bob'
  shirt: string
  accent?: string
  accessory?: 'headphones' | 'headband'
  item?: 'tablet' | 'chart'
}

export interface Character {
  id: string
  name: string
  role: string
  greeting: string
  /** いま何をしているか（会話ウィンドウの名札に「いま: 〇〇」と出す） */
  statusText: string
  /** 会話の選択肢。AIに送る質問文 */
  choices: string[]
  /** この選択肢が押されたら初期設定フローに入る */
  startsSetup?: string
  /** 選択肢ごとの受け答え */
  answers: Record<string, string>
  /** 選択肢以外を聞かれたときの返し */
  fallback: string
  /** 連携後に出す選択肢（設定がすんだ人向け） */
  connectedChoices?: string[]
  color: string
  look: Look
}

