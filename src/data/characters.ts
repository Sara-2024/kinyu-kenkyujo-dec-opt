// 研究員の一覧。名前・担当・挨拶・ドット絵の配色はすべてここに置く。
// 台詞の中で研究員の名前を呼ぶときは {{id}}（例: {{rin}}）と書く。
// 管理者画面で名前を変えたとき、SiteSettingsContext がまとめて差し替える。
// キャラ画像は後で本物のドット絵に差し替える前提なので、
// 見た目の定義（look）は PixelPerson が読む簡易パレットにしてある。

export interface Look {
  skin: string
  hair: string
  hairStyle: 'short' | 'bob' | 'ponytail' | 'slick' | 'bandana'
  /** 上着の形 */
  outfit: 'blazer' | 'suit' | 'vest' | 'work' | 'uniform'
  /** 上着の色 */
  clothes: string
  /** 中のシャツ（vest のときは袖の色にもなる） */
  inner?: string
  /** ネクタイ・ブローチ・スカーフ・光る縁取り */
  accent?: string
  pants: string
  skirt?: boolean
  accessory?: 'headset' | 'glasses' | 'goggles' | 'ribbon'
  /** 小物と、bandana の色 */
  accessoryColor?: string
  item?: 'tablet' | 'clipboard' | 'wrench'
  /** tablet の画面の色 */
  screen?: string
}

export interface Character {
  id: string
  name: string
  role: string
  greeting: string
  /** いま何をしているか（会話ウィンドウの名札に「いま: 〇〇」と出す） */
  statusText: string
  /** 研究所の名札に出す短い状態（英字）。アルゴだけは MT5 の状態で置き換わる */
  statusEn: string
  /** 会話の選択肢。AIに送る質問文 */
  choices: string[]
  /** この選択肢が押されたら初期設定（MT5との連携）フローに入る。担当は受付のユイだけ */
  startsSetup?: string
  /** この選択肢が押されたらメンバー紹介（ツアー）に入る */
  startsTour?: string
  /** この選択肢は、答えたあと別の担当へ案内するボタンを出す */
  handoff?: { choice: string; to: string; button: string }
  /** 選択肢ごとの受け答え */
  answers: Record<string, string>
  /** 選択肢以外を聞かれたときの返し */
  fallback: string
  /** 連携後に出す選択肢（設定がすんだ人向け） */
  connectedChoices?: string[]
  /** 連携済みで、前回が稼働中のまま戻ってきたとき */
  returningRunning?: string
  /** 連携済みで、前回が停止中のまま戻ってきたとき */
  returningStopped?: string
  /** 連携済みなのにブリッジが切れているとき */
  reconnecting?: string
  /**
   * この研究員は AI（/api/chat）が答える。担当の範囲は api/_lib/chat.ts に固定してあり、
   * 画面側は担当ぶんのデータ（aiContext.ts）だけを添えて聞く。
   * needsBridge の研究員は MT5 がつながっていないと AI に聞かず、noBridge を返す。
   */
  ai?: { needsBridge: boolean; noBridge?: string }
  color: string
  look: Look
}

